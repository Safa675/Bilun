"""Build demo-ready Tier A/B/C cohort listings after synthetic regen."""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
from typing import Any, Literal

from demo_config import load_demo_manifest, vignette_for_patient_index

DemoTier = Literal["A", "B", "C"]

TIER_BLURBS: dict[DemoTier, str] = {
    "A": "Showcase — credible for live demos; strict post-regen asserts.",
    "B": "Regression — pinned fault stories for CI and algorithm proofs.",
    "C": "Filler — generic randomized claims for cohort volume and diversity.",
}


def _patient_index(patient_id: str) -> str:
    return patient_id.rsplit("-", 1)[-1]


def _entry_for_index(
    index: str,
    *,
    tier: DemoTier,
    manifest: dict[str, Any],
) -> dict[str, Any]:
    scenario_by_index = manifest.get("scenario_by_index") or {}
    scenario_tag = scenario_by_index.get(index)
    vignette = vignette_for_patient_index(index)
    patient_id = f"SENTETIK-HASTA-{index}"
    landing = str(manifest.get("default_landing_index") or "").strip()

    entry: dict[str, Any] = {
        "patient_id": patient_id,
        "patient_index": index,
        "tier": tier,
        "scenario_tag": scenario_tag,
        "fault": vignette.fault if vignette else None,
        "department": vignette.department if vignette else None,
        "primary_icd10": vignette.primary_icd10 if vignette else None,
        "is_default_landing": index == landing,
        "demo_ready": tier == "A",
    }
    if vignette and vignette.golden is not None:
        entry["has_golden_bands"] = True
    return entry


def build_cohort_tier_report(
    *,
    num_patients: int,
    seed: int,
    dataset_id: str,
) -> dict[str, Any]:
    """Classify generated patients into Tier A / B / C for demo prep."""
    manifest = load_demo_manifest()
    tier_a = {str(i) for i in (manifest.get("tier_a_patient_indices") or [])}
    tier_b = {str(i) for i in (manifest.get("tier_b_patient_indices") or [])}
    landing = str(manifest.get("default_landing_index") or "").strip()
    landing_patient_id = f"SENTETIK-HASTA-{landing}" if landing else None

    tier_a_entries: list[dict[str, Any]] = []
    tier_b_entries: list[dict[str, Any]] = []
    tier_c_entries: list[dict[str, Any]] = []

    for i in range(1, num_patients + 1):
        index = f"{i:04d}"
        if index in tier_a:
            tier_a_entries.append(_entry_for_index(index, tier="A", manifest=manifest))
        elif index in tier_b:
            tier_b_entries.append(_entry_for_index(index, tier="B", manifest=manifest))
        else:
            tier_c_entries.append(_entry_for_index(index, tier="C", manifest=manifest))

    return {
        "generated_at": dt.datetime.now(dt.UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z"),
        "dataset_id": dataset_id,
        "seed": seed,
        "num_patients": num_patients,
        "default_landing_patient_id": landing_patient_id,
        "default_landing_scenario_tag": (manifest.get("scenario_by_index") or {}).get(landing),
        "tier_descriptions": TIER_BLURBS,
        "counts": {
            "tier_a": len(tier_a_entries),
            "tier_b": len(tier_b_entries),
            "tier_c": len(tier_c_entries),
        },
        "tier_a": tier_a_entries,
        "tier_b": tier_b_entries,
        "tier_c": tier_c_entries,
    }


def render_cohort_tier_markdown(report: dict[str, Any]) -> str:
    """Human-readable demo cheat sheet."""
    lines: list[str] = [
        "# Synthetic demo cohort — Tier A / B / C",
        "",
        f"**Dataset:** `{report['dataset_id']}`  ",
        f"**Generated:** {report['generated_at']}  ",
        f"**Seed:** `{report['seed']}`  ",
        f"**Patients:** {report['num_patients']} "
        f"(A={report['counts']['tier_a']}, "
        f"B={report['counts']['tier_b']}, "
        f"C={report['counts']['tier_c']})",
        "",
        "## Default demo landing",
        "",
    ]

    landing_id = report.get("default_landing_patient_id")
    landing_tag = report.get("default_landing_scenario_tag")
    if landing_id:
        lines.append(f"- **Patient:** `{landing_id}`")
        if landing_tag:
            lines.append(f"- **Scenario:** `{landing_tag}`")
    else:
        lines.append("- _(not configured in demo_manifest.json)_")

    lines.extend(
        [
            "",
            "## Tier guide",
            "",
            f"- **Tier A** — {TIER_BLURBS['A']}",
            f"- **Tier B** — {TIER_BLURBS['B']}",
            f"- **Tier C** — {TIER_BLURBS['C']}",
            "",
            "> Regenerated by `python scripts/synthetic/generate_sut_synthetic_data_v2.py`. "
            "Machine-readable copy: `demo_cohort_tiers.json`.",
            "",
        ]
    )

    def _section(title: str, tier_key: str, entries: list[dict[str, Any]]) -> None:
        lines.append(f"## {title} ({len(entries)})")
        lines.append("")
        if not entries:
            lines.append("_None in this cohort._")
            lines.append("")
            return
        lines.append("| Patient | Scenario | Fault | Notes |")
        lines.append("|---------|----------|-------|-------|")
        for row in entries:
            pid = row["patient_id"]
            tag = row.get("scenario_tag") or "—"
            fault = row.get("fault") or "—"
            notes: list[str] = []
            if row.get("is_default_landing"):
                notes.append("**default landing**")
            if row.get("department"):
                notes.append(row["department"])
            if row.get("primary_icd10"):
                notes.append(row["primary_icd10"])
            if row.get("has_golden_bands"):
                notes.append("golden ₺ bands")
            note_cell = "; ".join(notes) if notes else "—"
            lines.append(f"| `{pid}` | `{tag}` | {fault} | {note_cell} |")
        lines.append("")

    _section("Tier A — showcase (demo-ready)", "tier_a", report.get("tier_a") or [])
    _section("Tier B — regression pins", "tier_b", report.get("tier_b") or [])

    tier_c = report.get("tier_c") or []
    lines.append(f"## Tier C — filler ({len(tier_c)})")
    lines.append("")
    if tier_c:
        ids = ", ".join(f"`{row['patient_id']}`" for row in tier_c)
        lines.append(ids)
    else:
        lines.append("_None in this cohort._")
    lines.append("")

    return "\n".join(lines)


def write_cohort_tier_artifacts(
    *,
    synthetic_root: Path,
    report: dict[str, Any],
) -> tuple[Path, Path]:
    """Write JSON + Markdown tier listings under data/synthetic/."""
    synthetic_root.mkdir(parents=True, exist_ok=True)
    json_path = synthetic_root / "demo_cohort_tiers.json"
    md_path = synthetic_root / "DEMO_COHORT.md"

    json_path.write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    md_path.write_text(render_cohort_tier_markdown(report), encoding="utf-8")
    return json_path, md_path


def main() -> None:
    """Regenerate tier listing files without re-running the full generator."""
    import argparse

    from constants import DEFAULT_OUTPUT_DIR, SEED

    parser = argparse.ArgumentParser(
        description="Write demo_cohort_tiers.json + DEMO_COHORT.md from demo_manifest",
    )
    parser.add_argument("--num-patients", type=int, default=50)
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument(
        "--output-dir",
        type=str,
        default=str(DEFAULT_OUTPUT_DIR.parent),
        help="data/synthetic root (parent of sut/)",
    )
    args = parser.parse_args()
    dataset_id = f"sentetik_sut_v2_{args.num_patients}_hasta"
    report = build_cohort_tier_report(
        num_patients=args.num_patients,
        seed=args.seed,
        dataset_id=dataset_id,
    )
    json_path, md_path = write_cohort_tier_artifacts(
        synthetic_root=Path(args.output_dir),
        report=report,
    )
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
