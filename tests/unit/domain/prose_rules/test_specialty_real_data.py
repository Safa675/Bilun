"""Pytest integration for specialty-scope validation against real ILAY data.

Loads golden cases from data/gazette/prose_rules/golden/ilay/specialty_ilay_*.json
and asserts that Bilun's drug_indication engine produces the expected
``prescriber_specialty_mismatch`` violation for each.

These tests are REGRESSION tests, not clinical-correctness tests. They lock
in the engine's current behavior on real prescription data so that future
changes (especially to ``_specialty_matches``) are forced to update the
golden dataset explicitly rather than silently changing what fires.

The golden dataset was generated by ``scripts/validation/validate_specialty_rules.py``
+ ``scripts/validation/build_golden_dataset.py --specialty``. See
``scripts/validation/README.md`` for the honest findings, including the known
``Kalp ve Damar Cerrahisi`` substring-collision issue that surfaces here.
"""

from __future__ import annotations

import json
from datetime import date
from decimal import Decimal
from pathlib import Path

import pytest

from src.bilun.domain.claims.models import ClaimHeader, DrugClaimLine
from src.bilun.domain.prose_rules.drug_indication import (
    evaluate_drug_indication_line,
    list_drug_indication_rules,
)

pytestmark = pytest.mark.unit

_REPO = Path(__file__).resolve().parents[4]
_GOLDEN_DIR = _REPO / "data/gazette/prose_rules/golden/ilay"

# Collect every specialty_ilay_*.json file at import time
_GOLDEN_FILES = sorted(_GOLDEN_DIR.glob("specialty_ilay_*.json"))


def _load_all_golden_samples() -> list[dict]:
    """Load and flatten all specialty golden samples across section files."""
    all_samples: list[dict] = []
    for path in _GOLDEN_FILES:
        payload = json.loads(path.read_text(encoding="utf-8"))
        for sample in payload.get("samples", []):
            sample["_source_file"] = path.name
            all_samples.append(sample)
    return all_samples


_ALL_SAMPLES = _load_all_golden_samples()

# Build a rule-id → rule dict lookup once (rules corpus is cached by lru_cache)
_RULES_BY_ID: dict[str, dict] = {
    r.get("rule_id"): r for r in list_drug_indication_rules() if r.get("prescriber_specialties")
}


def _claim(*, primary_icd10: str, department: str = "bilinmiyor") -> ClaimHeader:
    return ClaimHeader(
        claim_id="C-SPECIALTY-TEST",
        patient_id="P1",
        episode_id="E1",
        claim_type="ayakta",
        facility_tier="3",
        provider_type="ozel",
        department=department,
        admission_date=date(2026, 1, 1),
        discharge_date=date(2026, 1, 1),
        claim_start_date=date(2026, 1, 1),
        claim_end_date=date(2026, 1, 1),
        primary_icd10=primary_icd10,
        package_candidate=False,
        expected_total_billed_try=Decimal("0"),
        expected_total_payable_try=Decimal("0"),
        expected_denial_reason="",
        scenario_tag="specialty-ilay-test",
    )


def _drug_line(*, drug_name: str, prescriber_specialty: str | None = None) -> DrugClaimLine:
    return DrugClaimLine(
        drug_claim_line_id="D-SPECIALTY-TEST",
        prescription_id="RX-SPECIALTY-TEST",
        claim_id="C-SPECIALTY-TEST",
        patient_id="P1",
        episode_id="E1",
        drug_claim_date=date(2026, 1, 2),
        drug_name=drug_name,
        drug_code="",
        barkod="",
        equivalence_group="",
        quantity=1,
        unit_price_try=Decimal("0"),
        billed_amount_try=Decimal("0"),
        expected_payable_try=Decimal("0"),
        discount_tier_expected=Decimal("0"),
        denial_reason_expected="",
        rule_trace_expected="",
        prescriber_specialty=prescriber_specialty,
    )


def test_specialty_golden_files_loaded() -> None:
    """Sanity: at least one specialty golden file was found."""
    assert _GOLDEN_FILES, (
        f"No specialty_ilay_*.json files found in {_GOLDEN_DIR}. "
        "Run scripts/validation/build_golden_dataset.py --specialty first."
    )


def test_specialty_golden_samples_exist() -> None:
    """Sanity: the loaded golden files contain actual samples."""
    assert _ALL_SAMPLES, "Specialty golden files exist but contain no samples."


@pytest.mark.parametrize(
    ("sample",),
    [(s,) for s in _ALL_SAMPLES],
    ids=lambda s: f"{s['_source_file']}::{s.get('rule_id', '?')}::{s.get('drug_name', '?')}",
)
def test_specialty_golden_case(sample: dict) -> None:
    """Each golden case must reproduce its expected prescriber_specialty_mismatch."""
    rule_id = sample["rule_id"]
    assert rule_id in _RULES_BY_ID, (
        f"Rule {rule_id} not found in loaded specialty-restricted rules corpus. "
        "The rule may have been removed or renamed."
    )
    rule = _RULES_BY_ID[rule_id]

    department = sample.get("prescriber_specialty") or "bilinmiyor"
    result = evaluate_drug_indication_line(
        drug_line=_drug_line(
            drug_name=sample["drug_name"],
            prescriber_specialty=department,
        ),
        claim=_claim(
            primary_icd10=sample.get("primary_icd10") or "Z00.0",
            department=department,
        ),
        diagnoses=(),
        rules=[rule],
    )

    expected_kind = sample.get("expect_violation")
    assert expected_kind == "prescriber_specialty_mismatch", sample

    assert result is not None, (
        f"Expected prescriber_specialty_mismatch for {sample['drug_name']} "
        f"prescribed by '{department}', but engine returned None."
    )
    assert result["violation_kind"] == "prescriber_specialty_mismatch", sample
    assert result["rule_id"] == rule_id, sample
