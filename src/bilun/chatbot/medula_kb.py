# ── Retrieval ─────────────────────────────────────────────────────────────────

def _normalize(text: str) -> str:
    return text.lower().strip()


def _tokenize(text: str) -> set[str]:
    tokens = re.split(r"[\s.,;:!?()\-/]+", _normalize(text))
    return {t for t in tokens if len(t) >= 2}


def search_known_codes(query: str) -> list[dict[str, Any]]:
    """Search known numeric error codes mentioned in the query."""
    codes = re.findall(r"\b(\d{4})\b", query)
    results: list[dict[str, Any]] = []
    seen: set[str] = set()
    for code in codes:
        if code in KNOWN_CODES and code not in seen:
            seen.add(code)
            results.append({"code": code, **KNOWN_CODES[code]})
    return results


def search_rejection_categories(query: str, top_n: int = 3) -> list[dict[str, Any]]:
    """Keyword-match user query against rejection categories. Returns top N matches."""
    tokens = _tokenize(query)
    scored: list[tuple[int, dict[str, Any]]] = []
    for cat in REJECTION_CATEGORIES:
        kw_tokens: set[str] = set()
        for kw in cat.get("keywords", []):
            kw_tokens |= _tokenize(kw)
        overlap = len(tokens & kw_tokens)
        if overlap > 0:
            scored.append((overlap, cat))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [item for _, item in scored[:top_n]]


def search_workflow_stage(query: str) -> dict[str, Any] | None:
    """Detect which MEDULA workflow stage the query is about."""
    stage_keywords: dict[str, list[str]] = {
        "hasta_kabul": ["hasta kabul", "admission", "provizyon", "takipNo",
                         "müstehaklık", "sevk", "biyometrik", "ekds"],
        "hizmet_kayit": ["hizmet kayıt", "service registration", "hizmet kaydı",
                          "sut kodu", "ilaç", "malzeme", "barkod", "rapor",
                          "tanı", "doktor", "branş", "kota"],
        "fatura_kayit": ["fatura", "invoice", "ödeme", "payment", "kesinti",
                          "taburcu", "105 gün", "yatış"],
    }
    tokens = _tokenize(query)
    best_stage: str | None = None
    best_score = 0
    for stage, keywords in stage_keywords.items():
        kw_tokens: set[str] = set()
        for kw in keywords:
            kw_tokens |= _tokenize(kw)
        score = len(tokens & kw_tokens)
        if score > best_score:
            best_score = score
            best_stage = stage
    if best_stage and best_score > 0:
        return {"stage": best_stage, **WORKFLOW_STAGES[best_stage]}
    return None


def search_medula(query: str) -> dict[str, Any]:
    """Main MEDULA search entry point. Returns structured results for context assembly.

    Args:
        query: The user's last message (Turkish or English).

    Returns:
        Dict with keys: known_codes, rejection_categories, workflow_stage.
        Each may be empty if nothing matched.
    """
    return {
        "known_codes": search_known_codes(query),
        "rejection_categories": search_rejection_categories(query, top_n=3),
        "workflow_stage": search_workflow_stage(query),
    }
